using System.Text.Json;
using CapabilityExplorer.Extractors.CSharp;
using Xunit;

namespace CapabilityExplorer.Extractors.Tests;

public sealed class CSharpCalculationTests : IDisposable
{
    private const string Sha = "0123456789abcdef0123456789abcdef01234567";
    private const string RatioSource = """
        namespace Synthetic;
        public static class Ratios
        {
            public static int Ratio(int numerator, int denominator) => numerator / denominator;
        }
        """;
    private const string RatioKey = "cs|synthetic|Synthetic|M:Synthetic.Ratios.Ratio(System.Int32,System.Int32)";
    private readonly string _root = Directory.CreateTempSubdirectory("ce-calc-").FullName;

    public void Dispose() => Directory.Delete(_root, recursive: true);

    [Fact]
    public void Division_emits_typed_ir_with_ordered_parameter_inputs()
    {
        var records = Extract(("Ratios.cs", RatioSource));

        AssertMethod(records, RatioKey);
        var calculation = Assert.Single(OfKind(records, "calculation"));
        Assert.Equal(RatioKey, calculation.GetProperty("symbolKey").GetString());
        AssertDivision(calculation);
        AssertJson("""{"type":"int32","unit":{"status":"unknown"}}""", calculation.GetProperty("output"));
        var zero = calculation.GetProperty("attributes").GetProperty("zeroDenominator");
        Assert.Equal("known", zero.GetProperty("status").GetString());
        Assert.Equal("throws", zero.GetProperty("value").GetString());
        Assert.Equal("System.DivideByZeroException", zero.GetProperty("detail").GetProperty("exception").GetString());
    }

    [Fact]
    public void Plain_arithmetic_helper_retains_method_without_becoming_a_calculation()
    {
        var records = Extract(("Arithmetic.cs", """
            namespace Synthetic;
            public static class Arithmetic
            {
                public static int ScaleAndAdd(int value, int offset) => value * 2 + offset;
            }
            """));

        AssertMethod(records, "cs|synthetic|Synthetic|M:Synthetic.Arithmetic.ScaleAndAdd(System.Int32,System.Int32)");
        Assert.Empty(OfKind(records, "calculation"));
    }

    [Fact]
    public void Unsupported_loop_preserves_resolved_calls_and_does_not_change_supported_neighbor()
    {
        var baseline = Assert.Single(OfKind(Extract(("Ratios.cs", RatioSource)), "calculation"));
        var records = Extract(("Ratios.cs", RatioSource), ("Loops.cs", """
            namespace Synthetic;
            public static class Loops
            {
                public static int LoopAverage(int[] values)
                {
                    int total = 0;
                    for (int i = 0; i < values.Length; i++)
                    {
                        total += Scale(values[i]);
                    }
                    return total / values.Length;
                }

                public static int Scale(int value) => value * 2;
            }
            """));
        const string loopKey = "cs|synthetic|Synthetic|M:Synthetic.Loops.LoopAverage(System.Int32[])";
        const string helperKey = "cs|synthetic|Synthetic|M:Synthetic.Loops.Scale(System.Int32)";

        AssertMethod(records, loopKey);
        AssertMethod(records, helperKey);
        AssertMethod(records, RatioKey);
        var call = Assert.Single(OfKind(records, "edge"), r =>
            r.GetProperty("relation").GetString() == "CALLS" && r.GetProperty("from").GetString() == loopKey);
        Assert.Equal(helperKey, call.GetProperty("to").GetString());
        Assert.Equal("resolved", call.GetProperty("resolution").GetString());

        // The division after the unsupported loop must not become an approximation.
        var calculation = Assert.Single(OfKind(records, "calculation"));
        Assert.Equal(RatioKey, calculation.GetProperty("symbolKey").GetString());
        AssertDivision(calculation);
        foreach (var property in new[] { "expr", "inputs", "output", "irHash" })
        {
            AssertJson(baseline.GetProperty(property).GetRawText(), calculation.GetProperty(property));
        }
    }

    [Theory]
    [InlineData("Generated.g.cs", "")]
    [InlineData("Generated.designer.cs", "")]
    [InlineData("Generated.cs", "// <auto-generated/>\n")]
    public void Generated_declarations_are_retained_but_their_division_is_not_a_calculation(string filename, string header)
    {
        var records = Extract(("Ratios.cs", RatioSource), (filename, header + """
            namespace Synthetic;
            public static class Generated
            {
                public static int Quotient(int numerator, int denominator) => numerator / denominator;
            }
            """));
        const string generatedKey = "cs|synthetic|Synthetic|M:Synthetic.Generated.Quotient(System.Int32,System.Int32)";

        var method = AssertMethod(records, generatedKey);
        Assert.True(method.GetProperty("generated").GetBoolean());
        var type = Assert.Single(OfKind(records, "node"), r =>
            r.GetProperty("symbolKey").GetString() == "cs|synthetic|Synthetic|T:Synthetic.Generated");
        Assert.True(type.GetProperty("generated").GetBoolean());
        var evidence = Assert.Single(method.GetProperty("evidence").EnumerateArray());
        var declaration = Assert.Single(OfKind(records, "evidence"), r =>
            r.GetProperty("id").GetString() == evidence.GetString());
        Assert.Equal(filename, declaration.GetProperty("path").GetString());

        var neighbor = AssertMethod(records, RatioKey);
        Assert.False(neighbor.TryGetProperty("generated", out _));
        var calculation = Assert.Single(OfKind(records, "calculation"));
        Assert.Equal(RatioKey, calculation.GetProperty("symbolKey").GetString());
        AssertDivision(calculation);
    }

    private JsonElement[] Extract(params (string Name, string Text)[] files)
    {
        var source = Path.Combine(_root, Guid.NewGuid().ToString("N"));
        Directory.CreateDirectory(source);
        File.WriteAllText(Path.Combine(source, "Synthetic.csproj"), """
            <Project Sdk="Microsoft.NET.Sdk">
              <PropertyGroup><TargetFramework>net10.0</TargetFramework></PropertyGroup>
            </Project>
            """);
        foreach (var (name, text) in files)
        {
            File.WriteAllText(Path.Combine(source, name), text);
        }

        var packs = Path.GetFullPath(Path.Combine(
            System.Runtime.InteropServices.RuntimeEnvironment.GetRuntimeDirectory(), "..", "..", "..", "packs"));
        var result = Assert.Single(new CSharpExtractor(new ExtractorOptions(
            source, "synthetic", Sha, PackagesRoot: null, ReferencePacks: packs)).Extract());
        var records = result.Jsonl.Split('\n', StringSplitOptions.RemoveEmptyEntries).Select(line =>
        {
            using var document = JsonDocument.Parse(line);
            return document.RootElement.Clone();
        }).ToArray();
        // Missing framework references or invalid snippets must fail the test, not exercise a partial compilation.
        Assert.Empty(OfKind(records, "diagnostic"));
        return records;
    }

    private static IEnumerable<JsonElement> OfKind(IEnumerable<JsonElement> records, string kind) =>
        records.Where(r => r.GetProperty("kind").GetString() == kind);

    private static JsonElement AssertMethod(IEnumerable<JsonElement> records, string key)
    {
        var method = Assert.Single(OfKind(records, "node"), r => r.GetProperty("symbolKey").GetString() == key);
        Assert.Equal("Method", method.GetProperty("nodeKind").GetString());
        return method;
    }

    private static void AssertDivision(JsonElement calculation)
    {
        AssertJson("""[{"ref":"$0","type":"int"},{"ref":"$1","type":"int"}]""", calculation.GetProperty("inputs"));
        AssertJson("""
            {"op":"bin","o":"/","type":"int32","l":{"op":"var","ref":"$0"},"r":{"op":"var","ref":"$1"}}
            """, calculation.GetProperty("expr"));
    }

    private static void AssertJson(string expected, JsonElement actual)
    {
        using var document = JsonDocument.Parse(expected);
        Assert.True(JsonElement.DeepEquals(document.RootElement, actual),
            $"Expected {expected}; actual {actual.GetRawText()}");
    }
}
