import ts from "typescript";
import type { Props } from "./builder.ts";
import { isFunctionInit, isModuleLevel, nameOf, type Ctx } from "./context.ts";

const has = (n: ts.Node, kind: ts.SyntaxKind) => !!ts.canHaveModifiers(n) && !!ts.getModifiers(n)?.some((m) => m.kind === kind);
const exported = (n: ts.Node) => has(n, ts.SyntaxKind.ExportKeyword) || (ts.isVariableDeclaration(n) && has(n.parent.parent, ts.SyntaxKind.ExportKeyword));
const isAsync = (n: ts.Node) => has(n, ts.SyntaxKind.AsyncKeyword);

const GENERATED = /<auto-generated|auto-generated|autogenerated|generated by|do not edit|do not make direct changes/i;

/** Marks generated files from their leading comment (`// This file was auto-generated by X 1.2`). */
export function detectGenerated(ctx: Ctx) {
  for (const sf of ctx.files) {
    const head = sf.text.slice(0, 600);
    const comments = head.match(/^(?:\s*(?:\/\/[^\n]*|\/\*[\s\S]*?\*\/))+/)?.[0] ?? "";
    if (GENERATED.test(comments) || /(^|\/)(__generated__|generated)\//.test(ctx.rel(sf.fileName))) {
      const by = /generated by ([\w@./-]+(?: v?\d[\w.-]*)?)/i.exec(comments)?.[1];
      ctx.generated.set(sf.fileName, by ?? true);
    }
  }
}

/** Declares Function, Type, Method and Variable nodes for module-level declarations. */
export function declare(ctx: Ctx) {
  for (const sf of ctx.files) {
    const generated = ctx.generated.get(sf.fileName);
    const isJs = /\.(m|c)?jsx?$/.test(sf.fileName);
    const visit = (statements: readonly ts.Statement[]) => {
      for (const s of statements) {
        if (ts.isModuleDeclaration(s) && s.body && ts.isModuleBlock(s.body)) visit(s.body.statements);
        else if (ts.isFunctionDeclaration(s)) fn(ctx, s, generated, isJs);
        else if (ts.isClassDeclaration(s)) cls(ctx, s, generated);
        else if (ts.isInterfaceDeclaration(s) || ts.isTypeAliasDeclaration(s) || ts.isEnumDeclaration(s)) typeDecl(ctx, s, generated);
        else if (ts.isVariableStatement(s)) {
          for (const d of s.declarationList.declarations) if (ts.isIdentifier(d.name)) variable(ctx, s, d, generated, isJs);
        }
      }
    };
    visit(sf.statements);
  }
  reExports(ctx);
}

function fn(ctx: Ctx, d: ts.FunctionDeclaration, generated: string | true | undefined, isJs: boolean) {
  const key = ctx.keyOf(d);
  if (!key) return;
  const props: Props = { exported: exported(d) || undefined, async: isAsync(d) || undefined };
  if (props.exported === undefined) props.exported = false;
  if (isJs) {
    props.language = "javascript";
    if (ts.getJSDocTags(d).some((t) => ts.isJSDocParameterTag(t) || ts.isJSDocReturnTag(t))) props.typedBy = "jsdoc";
  }
  ctx.b.node(key, "Function", nameOf(d)!, [ctx.headerEv(d)], { generated: !!generated, props });
  // Overloads: one symbol, one evidence per declaration, signatures listed.
  const decls = ctx.checker.getSymbolAtLocation(d.name ?? d)?.declarations?.filter(ts.isFunctionDeclaration) ?? [];
  const overloads = decls.filter((x) => !x.body);
  if (overloads.length > 0 && d === decls[0]) {
    ctx.b.setNodeProp(key, "overloads", overloads.map((o) => signatureText(o)));
  }
}

function signatureText(d: ts.SignatureDeclaration) {
  const text = d.getText();
  return text.slice(text.indexOf("(")).replace(/;\s*$/, "");
}

function cls(ctx: Ctx, c: ts.ClassDeclaration, generated: string | true | undefined) {
  const key = ctx.keyOf(c);
  if (!key) return;
  const props: Props = { typeKind: "class", exported: exported(c) };
  if (typeof generated === "string") props.generator = generated;
  const evidence = [ctx.headerEv(c)];
  // A generated class also points at the generator banner, the proof that it is generated.
  const sf = c.getSourceFile();
  if (generated) {
    const text = ctx.readRepoFile(ctx.rel(sf.fileName));
    const banner = /^.*generated.*$/im.exec(text);
    if (banner) evidence.unshift(ctx.textEv(ctx.rel(sf.fileName), text, banner.index, banner[0].trimEnd().length));
  }
  ctx.b.node(key, "Type", c.name!.text, evidence, { generated: !!generated, props });
  heritage(ctx, c, key);
  classConstructor(ctx, c, key, generated);
  for (const m of c.members) {
    const name = nameOf(m);
    if (!name) continue;
    if (ts.isMethodDeclaration(m) || ts.isGetAccessor(m) || ts.isSetAccessor(m) || (ts.isPropertyDeclaration(m) && isFunctionInit(m.initializer))) {
      const mk = ctx.keyOf(m);
      if (!mk) continue;
      const mprops: Props = {};
      if (has(m, ts.SyntaxKind.PrivateKeyword) || ts.isPrivateIdentifier(m.name)) mprops.accessibility = "private";
      else if (has(m, ts.SyntaxKind.ProtectedKeyword)) mprops.accessibility = "protected";
      if (has(m, ts.SyntaxKind.StaticKeyword)) mprops.static = true;
      if (isAsync(m) || (ts.isPropertyDeclaration(m) && m.initializer && isAsync(m.initializer))) mprops.async = true;
      const operationId = /operationId:\s*([\w.-]+)/.exec(ts.getJSDocCommentsAndTags(m).map((j) => j.getText()).join("\n"))?.[1];
      if (operationId) mprops.operationId = operationId;
      ctx.b.node(mk, "Method", name, [ctx.headerEv(m)], { generated: !!generated, props: mprops });
      ctx.b.edge({ from: key, rel: "DECLARES", to: mk, evidence: [ctx.headerEv(m)] });
    }
  }
}

function classConstructor(ctx: Ctx, c: ts.ClassDeclaration, owner: string, generated: string | true | undefined) {
  const declarations = c.members.filter(ts.isConstructorDeclaration);
  const implementation = declarations.find(declaration => declaration.body) ?? declarations[0];
  if (!implementation) return;
  const key = ctx.keyOf(implementation);
  if (!key) return;
  const props: Props = { constructor: true, signature: implementation.parameters.map(parameter => parameter.getText()) };
  if (has(implementation, ts.SyntaxKind.PrivateKeyword)) props.accessibility = "private";
  else if (has(implementation, ts.SyntaxKind.ProtectedKeyword)) props.accessibility = "protected";
  const overloads = declarations.filter(declaration => !declaration.body);
  if (overloads.length) props.overloads = overloads.map(declaration => signatureText(declaration));
  const evidence = declarations.map(declaration => ctx.headerEv(declaration));
  ctx.b.node(key, "Method", c.name!.text, evidence, { generated: !!generated, props });
  ctx.b.edge({ from: owner, rel: "DECLARES", to: key, evidence });
}

function heritage(ctx: Ctx, c: ts.ClassDeclaration | ts.InterfaceDeclaration, key: string) {
  for (const clause of c.heritageClauses ?? []) {
    for (const t of clause.types) {
      const decl = ctx.resolveSymbol(t.expression)?.declarations?.[0];
      const target = decl && ctx.keyOf(decl, "type");
      if (!target) continue;
      const rel = clause.token === ts.SyntaxKind.ImplementsKeyword || (ts.isClassDeclaration(c) && decl && ts.isInterfaceDeclaration(decl)) ? "IMPLEMENTS" : "INHERITS";
      ctx.b.edge({ from: key, rel, to: target, evidence: [ctx.ev(t)] });
    }
  }
}

function typeDecl(ctx: Ctx, d: ts.InterfaceDeclaration | ts.TypeAliasDeclaration | ts.EnumDeclaration, generated: string | true | undefined) {
  const key = ctx.keyOf(d, "type");
  if (!key) return;
  const typeKind = ts.isInterfaceDeclaration(d) ? "interface" : ts.isEnumDeclaration(d) ? "enum" : "alias";
  ctx.b.node(key, "Type", d.name.text, [ctx.headerEv(d)], { generated: !!generated, props: { typeKind, exported: exported(d) } });
  if (ts.isInterfaceDeclaration(d)) heritage(ctx, d, key);
}

function variable(ctx: Ctx, s: ts.VariableStatement, d: ts.VariableDeclaration, generated: string | true | undefined, isJs: boolean) {
  if (!isModuleLevel(d)) return;
  const key = ctx.keyOf(d);
  if (!key) return;
  const isFn = isFunctionInit(d.initializer);
  const props: Props = { exported: exported(d) };
  if (isFn && isAsync(d.initializer!)) props.async = true;
  if (isJs) props.language = "javascript";
  const evidence = s.declarationList.declarations.length === 1 ? ctx.ev(s) : ctx.ev(d);
  ctx.b.node(key, isFn ? "Function" : "Variable", (d.name as ts.Identifier).text, [evidence], { generated: !!generated, props });
}

/** `export { x } from "./y.js"`: the re-export is another declaration site of the same symbol. */
function reExports(ctx: Ctx) {
  for (const sf of ctx.files) {
    for (const s of sf.statements) {
      if (!ts.isExportDeclaration(s) || !s.moduleSpecifier || !s.exportClause || !ts.isNamedExports(s.exportClause)) continue;
      for (const spec of s.exportClause.elements) {
        const decl = ctx.resolveSymbol(spec.name)?.declarations?.[0];
        const key = decl && ctx.keyOf(decl);
        if (!key || !ctx.b.hasNode(key) || decl.getSourceFile() === sf) continue;
        ctx.b.node(key, "Function", "", [ctx.ev(s)]);
        const from = (ctx.b.nodeProps(key)?.reExportedFrom as string[] | undefined) ?? [];
        ctx.b.setNodeProp(key, "reExportedFrom", [...new Set([...from, ctx.rel(sf.fileName)])]);
      }
    }
  }
}
