import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
const output = '/work/.sandbox-cache/likec4-browser';
await mkdir(output, {recursive:true});
const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
const errors = [], external = [], measurements = [];
try {
  for (const [width,height] of [[5120,2160],[2560,1080],[1920,1080],[390,844]]) {
    const page = await browser.newPage({viewport:{width,height}, reducedMotion:'no-preference'});
    page.setDefaultTimeout(15000);
    console.log(`Checking ${width}×${height}`);
    page.on('pageerror',e=>errors.push(e.message));
    page.on('request',r=>{const u=new URL(r.url());if(u.protocol.startsWith('http') && u.hostname!=='host.docker.internal')external.push(r.url());});
    await page.goto('http://host.docker.internal:5091');
    await page.locator('.react-flow__node').first().waitFor();
    await page.evaluate(() => document.fonts.ready);
    await page.waitForTimeout(500); // allow the renderer's initial fit to settle
    assert.equal(await page.locator('.react-flow__node').count(), 10);
    const edgeCount=await page.locator('.react-flow__edge').count();
    assert.ok(edgeCount>0&&edgeCount<=12);
    assert.equal(await page.locator('.react-flow__node[data-id^="sql_scope_"]').count(),3,'overview shows logical resources, not SQL objects');
    const canvas=await page.locator('.canvas').boundingBox();
    const workspace=await page.locator('.diagram-workspace').boundingBox();
    assert.ok(workspace.width>width*.9, `workspace must use viewport width at ${width}`);
    const menu=await page.locator('.viewpoint-drawer').boundingBox();
    assert.ok(width>700?menu.x+menu.width<=canvas.x+1:menu.y+menu.height<=canvas.y+1,'permanent menu must not overlap canvas');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'spike horizontal page overflow');
    assert.equal(await page.getByRole('switch',{name:'Animation',exact:true}).isChecked(),false);
    assert.equal(await page.getByRole('switch',{name:'Orthogonal',exact:true}).isChecked(),true);
    assert.equal(await page.getByRole('switch',{name:'Dark mode',exact:true}).isChecked(),true);
    assert.equal(await page.locator('.spike').getAttribute('data-theme'),'dark');
    const nodePositions=()=>page.locator('.react-flow__node').evaluateAll(es=>es.map(e=>({id:e.dataset.id,transform:e.style.transform})));
    const positions=await nodePositions();
    const routes=()=>page.locator('.react-flow__edge-path').evaluateAll(es=>es.map(e=>e.getAttribute('d')));
    const orthoRoutes=await routes();
    await page.getByRole('switch',{name:'Orthogonal',exact:true}).uncheck();
    await page.waitForTimeout(300);
    assert.notDeepEqual(await routes(),orthoRoutes,'routing toggle changes rendered paths');
    assert.deepEqual(await nodePositions(),positions,'routing preserves node positions');
    await page.getByRole('switch',{name:'Orthogonal',exact:true}).check();
    await page.waitForTimeout(300);
    assert.deepEqual(await routes(),orthoRoutes,'orthogonal routing restored deterministically');
    await page.getByRole('switch',{name:'Dark mode',exact:true}).uncheck();
    assert.equal(await page.locator('.spike').getAttribute('data-theme'),'light');

    const paths=page.locator('.react-flow__edge-path');
    assert.ok((await paths.evaluateAll(es=>es.map(e=>getComputedStyle(e).animationName))).every(n=>n==='none'));
    await page.screenshot({path:`${output}/likec4-${width}.png`});
    const canvasBeforeMenu=await page.locator('.canvas').boundingBox();
    const viewportBefore=await page.locator('.react-flow__viewport').first().getAttribute('style');
    assert.equal(await page.locator('.viewpoint-drawer').getAttribute('data-open'),'true');
    await page.getByRole('button',{name:'Add Messaging dependencies to favorites',exact:true}).click();
    assert.ok((await page.getByRole('region',{name:'Favorite viewpoints'}).innerText()).includes('Messaging dependencies'));
    await page.screenshot({path:`${output}/likec4-menu-${width}.png`});
    assert.ok((await page.getByRole('region',{name:'Diagram legend'}).innerText()).includes('identity not established'));
    assert.equal(await page.locator('[data-ledger-key]').count(),12,'all authoritative colors visible by default');
    const swatches=await page.locator('[data-ledger-key]').evaluateAll(es=>es.map(e=>({hex:e.querySelector('span').textContent,color:getComputedStyle(e).backgroundColor})));
    for(const {hex,color} of swatches){const rgb=hex.slice(1).match(/../g).map(x=>parseInt(x,16));assert.equal(color,`rgb(${rgb.join(', ')})`);}
    assert.deepEqual(await page.locator('.canvas').boundingBox(),canvasBeforeMenu,'ledger does not resize canvas');
    await page.getByRole('button',{name:'Minimize ledger',exact:true}).click();
    assert.equal(await page.getByRole('region',{name:'Diagram legend'}).count(),0);
    await page.getByRole('button',{name:'Expand ledger',exact:true}).click();
    await page.getByRole('button',{name:'Minimize ledger',exact:true}).click();
    assert.equal(await page.locator('.react-flow__viewport').first().getAttribute('style'),viewportBefore,'menu and ledger actions must not move diagram');
    await page.getByRole('switch',{name:'Animation',exact:true}).check();
    assert.ok((await paths.evaluateAll(es=>es.map(e=>getComputedStyle(e).animationName))).some(n=>n==='ce-edge-flow'));
    await page.locator('.ce-motion-particle').first().waitFor();
    const moving = await paths.first().evaluate(async e => {const before=getComputedStyle(e).opacity;await new Promise(r=>setTimeout(r,120));return before!==getComputedStyle(e).opacity;});
    assert.ok(moving, 'enabled motion changes edge highlight');
    await page.getByRole('switch',{name:'Animation',exact:true}).uncheck();
    assert.equal(await page.locator('.ce-motion-particle').count(),0);
    assert.ok((await paths.evaluateAll(es=>es.map(e=>getComputedStyle(e).animationName))).every(n=>n==='none'));
    await page.getByRole('button',{name:'Diagram source',exact:true}).click();
    assert.ok((await page.locator('pre').textContent()).includes('metadata'));
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'source panel overflows page');
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download .c4'}).click();
    assert.equal((await downloadPromise).suggestedFilename(),'architecture.c4');
    await page.emulateMedia({reducedMotion:'reduce'});
    await page.waitForFunction(()=>[...document.querySelectorAll('input')].some(e=>e.disabled));
    assert.equal(await page.getByRole('switch',{name:'Animation',exact:true}).isDisabled(),true);
    assert.equal(await page.getByRole('switch',{name:'Animation',exact:true}).isChecked(),false);
    if (width === 1920) {
      await page.getByRole('button',{name:'Diagram source',exact:true}).click();
      await page.getByRole('switch',{name:'Dark mode',exact:true}).check();
      assert.equal(await page.locator('.spike').getAttribute('data-theme'),'dark');
      assert.equal(await page.locator('.react-flow__node-view-group').count(),3,'explicit repositories auto-group');
      const node=id=>page.locator(`.react-flow__node[data-id="${id}"]`);
      const clickHeader=async id=>{const box=await node(id).boundingBox();await page.mouse.click(box.x+30,box.y+12);};
      await page.waitForTimeout(500);
      const group=node('repository_2');
      const beforeA=await node('repository_2.n2').boundingBox(),beforeB=await node('repository_2.n3').boundingBox();
      const box=await group.boundingBox();
      await page.mouse.move(box.x+box.width/2,box.y+12);await page.mouse.down();
      await page.mouse.move(box.x+box.width/2+80,box.y+62,{steps:12});await page.mouse.up();
      await page.waitForTimeout(400);
      const afterA=await node('repository_2.n2').boundingBox(),afterB=await node('repository_2.n3').boundingBox();
      assert.ok(Math.abs(afterA.x-beforeA.x)>30,'group drag moves members');
      assert.ok(Math.abs((afterA.x-beforeA.x)-(afterB.x-beforeB.x))<2,'members move as one unit');
      await clickHeader('repository_2');
      await page.getByRole('button',{name:'Rename',exact:true}).click();
      await page.getByRole('textbox',{name:'Group name'}).fill('Worker context');
      await page.getByRole('button',{name:'Save group',exact:true}).click();
      await page.waitForTimeout(400);
      assert.ok((await group.innerText()).toLowerCase().includes('worker context'));
      await clickHeader('repository_2');
      await page.getByRole('button',{name:'Edit members',exact:true}).click();
      await node('sql_scope_2').click();
      await page.getByRole('button',{name:'Save group',exact:true}).click();
      await page.waitForTimeout(400);
      await clickHeader('repository_2');
      assert.ok((await page.locator('.group-context').innerText()).includes('3 members'));
      await page.screenshot({path:`${output}/likec4-group-dark.png`});
      await page.getByRole('button',{name:'Ungroup',exact:true}).click();
      await page.waitForTimeout(400);
      assert.equal(await page.locator('.react-flow__node-view-group').count(),2);
      await node('repository_2.n2').click();
      await node('sql_scope_2').click({modifiers:['Shift']});
      await page.getByRole('button',{name:'Group selection',exact:true}).click();
      await page.getByRole('textbox',{name:'Group name'}).fill('Review cluster');
      await page.getByRole('button',{name:'Save group',exact:true}).click();
      await page.waitForTimeout(300);
      assert.equal(await page.locator('.react-flow__node-view-group').count(),3);
      await page.reload();await page.locator('.react-flow__node').first().waitFor();
      assert.ok((await page.locator('.react-flow__node-view-group').allTextContents()).some(t=>t.toLowerCase().includes('review cluster')),'CRUD persists for same source snapshot');
      await page.getByRole('button',{name:'Minimize ledger',exact:true}).click();
      for(const viewpoint of ['index','applications','data','messaging','repository_0_detail','objects','sql_scope_0_detail','sql_scope_1_detail','sql_scope_2_detail','vertical','flow']) {
        await page.locator(`.viewpoint-drawer [data-view-id="${viewpoint}"]`).first().click();await page.waitForTimeout(400);
        assert.ok(await page.locator('.react-flow__node').count()>0,`${viewpoint} renders`);
        if(viewpoint==='objects'){assert.equal(await page.locator('.react-flow__node[data-id*="sql_scope_"][data-id*=".n"]').count(),5);await page.screenshot({path:`${output}/likec4-sql-objects.png`});}
      }
      assert.ok((await page.locator('.react-flow__node-view-group').allTextContents()).some(t=>t.toLowerCase().includes('review cluster')),'groups survive viewpoint changes');
      await page.locator('.viewpoint-drawer [data-view-id="data"]').first().click();
      assert.equal(await page.locator('.viewpoint-drawer').getAttribute('data-open'),'true','pinned menu stays open after navigation');
      await page.reload();await page.locator('.react-flow__node').first().waitFor();
      assert.equal(await page.locator('.viewpoint-drawer').getAttribute('data-open'),'true','menu remains visible on reload');
      assert.ok((await page.getByRole('region',{name:'Favorite viewpoints'}).innerText()).includes('Messaging dependencies'),'favorite persists');
      await page.getByRole('button',{name:'Remove Messaging dependencies from favorites',exact:true}).first().click();
      assert.ok(!(await page.getByRole('region',{name:'Favorite viewpoints'}).innerText()).includes('Messaging dependencies'),'favorite removable');
      await page.keyboard.press('Escape');
      assert.equal(await page.locator('.viewpoint-drawer').getAttribute('data-open'),'true','Escape does not hide permanent navigation');
    }
    measurements.push({app:'likec4',width,height,canvasWidth:canvas.width,nodes:10,edges:edgeCount});
    await page.close();

    const explorer=await browser.newPage({viewport:{width,height}});
    explorer.on('pageerror',e=>errors.push(e.message));
    await explorer.addInitScript(()=>localStorage.setItem('ce.capability',JSON.stringify('weekly-sales')));
    await explorer.goto('http://host.docker.internal:5090/#/architecture');
    await explorer.locator('.react-flow__node').first().waitFor();
    await explorer.waitForTimeout(500);
    const main=await explorer.locator('main').boundingBox();
    assert.ok(main.width>=width-2, `Explorer shell capped at ${width}`);
    assert.ok(await explorer.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), `Explorer horizontal page overflow at ${width}`);
    await explorer.screenshot({path:`${output}/explorer-${width}.png`});
    measurements.push({app:'explorer',width,height,mainWidth:main.width});
    await explorer.close();
  }
  assert.deepEqual(errors,[], 'browser exceptions');
  assert.deepEqual(external,[], 'spike must not fetch third-party resources');
  await writeFile(`${output}/measurements.json`,JSON.stringify(measurements,null,2)+'\n');
  console.log(JSON.stringify({passed:true,measurements},null,2));
} finally { await browser.close(); }
